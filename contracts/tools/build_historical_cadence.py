#!/usr/bin/env python3
"""Generate the optional "historical cadence" patch.

With contracts/Optional/MKSP_HistoricalCadence copied into GameData, each
Artemis contract is not offered before a set lead time ahead of the real-world
window in the research manifest (via contract-meta.json). Without the folder,
contracts stay capability-gated only (the default).

RP2000 calendar: UT 0 = 2000-01-01 00:00 UTC, real Gregorian calendar.
Usage: build_historical_cadence.py [--lead-quarters N] [--check]
"""
import datetime as dt, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
META = os.path.join(ROOT, "contracts", "manifest", "contract-meta.json")
OUT = os.path.join(ROOT, "contracts", "Optional", "MKSP_HistoricalCadence", "HistoricalCadence.cfg")
EPOCH = dt.datetime(2000, 1, 1, tzinfo=dt.timezone.utc)


def quarter_start(q, lead):
    y, n = int(q[:4]), int(q[-1])
    idx = y * 4 + (n - 1) - lead
    y, n = divmod(idx, 4)
    return dt.datetime(y, n * 3 + 1, 1, tzinfo=dt.timezone.utc)


def main():
    lead = 4
    if "--lead-quarters" in sys.argv:
        lead = int(sys.argv[sys.argv.index("--lead-quarters") + 1])
    meta = json.load(open(META))
    lines = [
        "// GENERATED by contracts/tools/build_historical_cadence.py - do not edit by hand.",
        "// Optional: copy this folder (MKSP_HistoricalCadence) into GameData to hold each",
        f"// Artemis contract until {lead} quarter(s) before its real-world window opens",
        f"// (research manifest v{meta['manifest_version']}, as of {meta['manifest_as_of']}).",
        "// Delete the folder to return to capability-only gating. Contracts already",
        "// offered or accepted are not affected.",
        "",
    ]
    n = 0
    for name, c in meta["contracts"].items():
        if not c.get("window"):
            continue
        when = quarter_start(c["window"]["start"], lead)
        ut = int((when - EPOCH).total_seconds())
        lines += [
            f"@CONTRACT_TYPE[{name}]:NEEDS[myKSP_Artemis]",
            "{",
            "\tREQUIREMENT",
            "\t{",
            "\t\tname = MKSP_HistoricalCadence",
            "\t\ttype = Expression",
            f"\t\texpression = UniversalTime() >= {ut}",
            f"\t\ttitle = Not before {when:%Y-%m-%d} (real window {c['window']['start']})",
            "\t}",
            "}",
            "",
        ]
        n += 1
    text = "\n".join(lines)
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        sys.exit(0 if cur == text else "HistoricalCadence.cfg is stale: rerun build_historical_cadence.py")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {n} gated contracts, lead {lead} quarters")


if __name__ == "__main__":
    main()
